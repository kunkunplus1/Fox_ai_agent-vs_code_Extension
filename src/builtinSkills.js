/**
 * 匹配 `/仿人` / `/humanize` 等内置斜杠技能并渲染注入块。
 * @param {string} raw 用户原始输入（如 "/仿人 把这篇文章改得自然点"）
 * @returns {string|null} 命中时返回注入文本；未命中返回 null
 */
function matchBuiltinSkillSlash(raw) {
  if (typeof raw !== 'string') return null;
  const m = /^\s*\/(仿人|humanize|美化|format|幻灯片|ppt|slides|简洁|说重点|concise|brief|重点)(\s+([\s\S]*))?$/i.exec(raw.trim());
  if (!m) return null;
  const kind = m[1].toLowerCase();
  const rest = (m[3] || '').trim();
  let name = '仿人技能';
  let body = HUMANIZE_BODY;
  if (kind === '美化' || kind === 'format') { name = '内容美化技能'; body = FORMAT_BODY; }
  if (kind === '幻灯片' || kind === 'ppt' || kind === 'slides') { name = 'PPT 制作技能'; body = PPT_BODY; }
  if (kind === '简洁' || kind === '说重点' || kind === 'concise' || kind === 'brief' || kind === '重点') { name = '输出精简技能'; body = CONCISE_BODY; }
  const block = [
    '<skill_content name="' + name + '">',
    '<skill_instructions>',
    body.trim(),
    '</skill_instructions>',
    '</skill_content>'
  ].join('\n');
  return rest ? block + '\n\n【本次要处理的文本/任务】\n' + rest : block;
}

